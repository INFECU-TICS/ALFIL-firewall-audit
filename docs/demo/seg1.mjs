import fs from "fs";
import { execFileSync } from "child_process";
import { newSession, caption, click, type, sleep, card, readEnv } from "./lib.mjs";
const WEB = "http://localhost:8090";
const env = readEnv(process.env.DEMO_ENV_FILE || "../../.env") // API_KEY del firewall de laboratorio (no se imprime);
const out = "out"; fs.mkdirSync(out, { recursive: true });
const shots = (p, n) => p.screenshot({ path: `${out}/s1_${n}.png` });
const s = await newSession(out, "seg1");
const { page } = s;
try {
  await card(page, "ALFIL", "Auditoría de firewalls Sophos v23 y servidor MCP para agentes de IA", 3500);
  await page.goto(WEB); await sleep(1200);
  await caption(page, "1 · Registrar una conexión", "Cada firewall se registra una vez; la API key se guarda cifrada.");
  await sleep(2200);
  await click(page, page.getByRole("button", { name: /Nueva conexión/ }));
  await sleep(800);
  await click(page, page.getByRole("button", { name: /API REST v23/ }));
  await type(page, page.getByPlaceholder("Ej. Cliente ABC - FW Principal"), "Firewall Demo");
  await type(page, page.getByPlaceholder("192.168.1.1"), process.env.DEMO_FW_HOST || "fw-demo.lab");
  await type(page, page.locator('input[type="password"]'), env.API_KEY, 25);
  await caption(page, "La API key se escribe en un campo protegido", "Activar «Disponible en MCP» permite que un agente consulte este firewall (solo lectura).");
  await click(page, page.getByLabel(/Disponible en MCP/));
  await sleep(1200);
  await click(page, page.getByRole("button", { name: "Probar conexión" }));
  await page.getByText("Conexión exitosa").waitFor({ timeout: 60000 });
  await caption(page, "Conexión verificada", "REST API v1 de SFOS v23");
  await sleep(2200); await shots(page, "form");
  await click(page, page.getByRole("button", { name: "Crear conexión" }));
  await sleep(1500);
  await caption(page, "2 · Auditar el firewall", "Un clic: ALFIL recolecta la configuración y la analiza.");
  await click(page, page.getByRole("button", { name: /Auditar/ }));
  await sleep(1500);
  await click(page, page.getByRole("button", { name: /Nueva auditoría/ }));
  await caption(page, "Auditando…", "En REST tarda unos segundos; en XML puede tardar minutos.");
  await page.getByTitle("Ver reporte").first().waitFor({ timeout: 180000 });
  await sleep(800);
  await click(page, page.getByTitle("Ver reporte").first());
  await page.getByText("Todos los hallazgos").waitFor({ timeout: 30000 });
  await sleep(1000);
  await caption(page, "Puntaje, severidades y datos del equipo", "El puntaje resume el estado; el detalle está en los hallazgos.");
  await page.mouse.wheel(0, 260); await sleep(2800); await shots(page, "report1");
  await caption(page, "Cada hallazgo trae su recomendación", "Críticos primero: administradores sin MFA, reglas Any→Any, sin log…");
  await page.mouse.wheel(0, 380); await sleep(3500); await shots(page, "findings");
  await page.mouse.wheel(0, 500); await sleep(2500);
  const hc = page.getByText(/Verificación de políticas del equipo/);
  await click(page, hc);
  await caption(page, "Verificación de políticas del propio Sophos (Health Check)", "Se muestra aparte y no altera el puntaje de ALFIL.");
  await page.mouse.wheel(0, 380); await sleep(3500); await shots(page, "healthcheck");
  const cov = page.getByText(/Alcance de la revisión/);
  await click(page, cov);
  await caption(page, "Alcance: lo que no se pudo evaluar", "El reporte no afirma nada sobre esas secciones.");
  await page.mouse.wheel(0, 300); await sleep(3200); await shots(page, "coverage");
  await page.mouse.wheel(0, -3000); await sleep(1200);
  await caption(page, "3 · Exportar el reporte", "Excel, PDF y ZIP (con JSON) para revisarlo antes de entregarlo.");
  s.ctx.on("page", (p) => setTimeout(() => p.close().catch(() => {}), 1500)); // la app abre la descarga con window.open
  await click(page, page.locator("button", { hasText: /^\s*PDF\s*$/ }));
  await sleep(1500);
  const rep = await s.ctx.request.get(`${WEB}/api/v1/audit/reports/1/export/pdf`);
  fs.writeFileSync(`${out}/reporte.pdf`, await rep.body());
  const xl = await s.ctx.request.get(`${WEB}/api/v1/audit/reports/1/export/excel`);
  fs.writeFileSync(`${out}/reporte.xlsx`, await xl.body());
  execFileSync("pdftoppm", ["-r", "80", "-png", `${out}/reporte.pdf`, `${out}/pdf`]);
  // Tapar en las imágenes del PDF lo que se enmascara en pantalla (DEMO_MASK_PDF: regex separadas por «;;»)
  if (process.env.DEMO_MASK_PDF) execFileSync("python3", ["mask_pdf_png.py", `${out}/reporte.pdf`, `${out}/pdf`, "80", ...process.env.DEMO_MASK_PDF.split(";;")]);
  for (const [n, cap] of [["1", "Reporte PDF: resumen y hallazgos con recomendación"], ["2", "Reporte PDF: Health Check, alcance y datos del sistema"]]) {
    const img = fs.readFileSync(`${out}/pdf-${n}.png`).toString("base64");
    await page.evaluate((b64) => { const d = document.createElement("div"); d.id = "__img"; d.style = "position:fixed;inset:0;z-index:2147483000;background:#374151;display:flex;justify-content:center;align-items:center";
      d.innerHTML = `<img src="data:image/png;base64,${b64}" style="height:640px;box-shadow:0 8px 30px rgba(0,0,0,.5)">`; document.body.appendChild(d); }, img);
    await caption(page, cap, "Fechas en español, severidades legibles y texto con símbolos seguro.");
    await sleep(4200);
    await page.evaluate(() => document.getElementById("__img")?.remove());
  }
  await caption(page, "Excel: hojas por tema", "Resumen, Hallazgos, Verificación Sophos, reglas, NAT, usuarios, objetos, TLS, web y Alcance.");
  await sleep(3000);
  await caption(page, "4 · Topología de red", "Zonas, interfaces, rutas y VPN a partir de la configuración.");
  await page.mouse.wheel(0, 600); await sleep(800);
  await click(page, page.getByTitle("Topología de red").first());
  await sleep(4500); await shots(page, "topology");
  await caption(page, "Se puede filtrar, mover y exportar a Mermaid", "No incluye ruteo dinámico: la API v1 no lo expone.");
  await sleep(3500);
  await page.goto(WEB); await sleep(1500);
  page.on("dialog", (d) => d.accept());
  await caption(page, "5 · Permisos del MCP", "Opcional: permitir que un agente PROPONGA cambios en este firewall (nunca borrados, siempre con confirmación).");
  await sleep(3000);
  await click(page, page.getByRole("switch", { name: /Permitir cambios con confirmación/ }));
  await sleep(2000);
  await caption(page, "6 · Conectar un agente de IA (MCP)", "Con una URL y un token por agente, sin instalar nada.");
  await sleep(2500);
  await click(page, page.getByRole("button", { name: /Conectar un agente/ }));
  await sleep(1000);
  await type(page, page.getByPlaceholder(/Nombre del agente/), "agente-demo");
  await caption(page, "Un token por agente, con nombre y caducidad", "Se puede revocar de forma individual.");
  await sleep(1800);
  const cb = page.getByLabel(/Permitir proponer cambios/);
  if (await cb.count()) { await click(page, cb); }
  await click(page, page.getByRole("button", { name: /Crear token para este agente/ }));
  await page.getByText(/Token «agente-demo» incluido/).waitFor({ timeout: 20000 });
  await sleep(1200);
  // El token aparece en el fragmento del agente: se guarda para la sesión real del agente (no se imprime)
  await click(page, page.getByRole("button", { name: "opencode", exact: true }));
  await sleep(1200);
  const snippet = await page.locator("pre").allInnerTexts();
  const m = snippet.join("\n").match(/alfil_mcp_[A-Za-z0-9_\-]+/);
  fs.writeFileSync(`${out}/token`, m ? m[0] : "");
  await caption(page, "Fragmento listo para opencode", "También hay fragmentos para Claude Code, Codex, Cursor y VS Code.");
  await sleep(3500); await shots(page, "token");
} catch (e) { await shots(page, "error").catch(() => {}); console.error("FALLO:", e.message.split("\n")[0]); }
const f = await s.close(); console.log("video:", f);
